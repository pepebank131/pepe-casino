export type TKey = keyof (typeof DICT)["en"]

interface I18nCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: TKey, vars?: Record<string, string | number>) => string
  /** Translate a case by id, falling back to the provided name. */
  tCase: (id: string, fallback: string) => string
}

const Ctx = createContext<I18nCtx | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en")

  // Restore saved language on mount. First-ever launch always defaults to
  // English regardless of the Telegram client's language — we no longer
  // auto-switch to ru/uk based on language_code.
  useEffect(() => {
    const saved = (typeof window !== "undefined" && localStorage.getItem("pepe_lang")) as Lang | null
    if (saved && DICT[saved]) {
      setLangState(saved)
    }
    // else: keep the "en" default from useState above.
  }, [])

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    if (typeof window !== "undefined") localStorage.setItem("pepe_lang", l)
  }, [])

  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>) => {
      let str: string = (DICT[lang] as Record<string, string>)[key] ?? (DICT.en as Record<string, string>)[key] ?? key
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v))
        }
      }
      return str
    },
    [lang],
  )

  // Case names are brand names and must stay in English in every language.
  const tCase = useCallback((_id: string, fallback: string) => fallback, [])

  return <Ctx.Provider value={{ lang, setLang, t, tCase }}>{children}</Ctx.Provider>
}

export function useT() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error("useT must be used within I18nProvider")
  return ctx
}
